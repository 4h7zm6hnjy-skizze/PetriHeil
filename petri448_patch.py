#!/usr/bin/env python3
"""Petri Heil Pro 4.4.8: narrowly-scoped repo update and preflight.
Run from repo root with: python3 petri448_patch.py
No existing user data, localStorage, IndexedDB or media files are modified.
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path
from datetime import date

ROOT = Path.cwd()
OLD, NEW = '4.4.7', '4.4.8'
PAGES = '''angelbegleiter.html angelschule.html angelstudio.html angelwerkzeuge.html datenschutz.html erweiterungen.html gewaesser.html gezeiten.html index.html installieren.html karte.html karten-detail.html kinderwelt.html lernspiele.html montagen.html offline-check.html petri370.html petri400.html petri410.html petri411-bilderpruefung.html petri420-quality.html petri420.html petri430-angeltag.html petri430-arten.html petri430-ausruestung.html petri430-beissindex.html petri430-fangbuch.html petri430-qualitaet.html petri430.html petri440.html praxis.html premium.html sicherung410.html system410.html update-rettung.html werkzeuge.html zentrale.html'''.split()
updated: dict[str,bytes] = {}

def original(path):
    p=ROOT/path
    if not p.is_file():raise ValueError(f'Missing source file: {path}')
    return p.read_bytes().decode('utf-8-sig')
def edit(path, new):
    if '\x00' in new:raise ValueError('NUL byte '+path)
    updated[path]=new.encode('utf-8')
def expect_once(s,src,path):
    n=s.count(src)
    if n!=1:raise ValueError(f'{path}: expected exactly one anchor, found {n}: {src[:50]}')

def patch():
    v=json.loads(original('version.json'))
    if v.get('version')!=OLD:raise ValueError(f"Expected release {OLD}, got {v.get('version')}. Aborting without editing files.")
    assets={p.name for p in ROOT.iterdir() if p.is_file()}
    if len(list(ROOT.glob('*.html')))<37 or len(list(ROOT.glob('*.webp')))<225:
        raise ValueError('Repo incomplete (HTML or image media files missing)')

    for name in PAGES:
        s=original(name)
        m=re.search(r'(<meta\s+name="petri-app-version"\s+content=")[0-9.]+("\s*/?>)',s)
        if not m:raise ValueError(f'{name}: missing version meta')
        s=s[:m.start()]+m.group(1)+NEW+m.group(2)+s[m.end():]
        if name in ('karte.html','premium.html'):
            if './detailkarte.html' not in s:raise ValueError(name+': expected known dead link')
            s=s.replace('./detailkarte.html','./karten-detail.html')
        expect_once(s,'petri445-nav.js?v=4.4.7',name)
        s=s.replace('petri445-nav.js?v=4.4.7','petri445-nav.js?v='+NEW)
        # Main app pages reference exact release versions in other URLs and labels.
        if name in ('index.html','petri440.html'):
            s=s.replace(OLD,NEW)
        edit(name,s)

    updater=original('petri-updater.js')
    anchor='  function attachCard(){'
    expect_once(updater,anchor,'petri-updater.js')
    add=r'''  // Hide the obsolete update status generated by the legacy 2.x app.
  // The stable updater below is the single source of truth for version checks.
  function clearLegacyStatus(card){
    for(const node of card.querySelectorAll('p,small,span,b,strong,button,a')){
      if(node.closest('#petri-stable-update'))continue;
      const label=(node.textContent||'').replace(/\s+/g,' ').trim();
      if(node.children.length===0 &&
         (/^Eine neuere Version\s+\d+\.\d+\.\d+\s+ist gemeldet\b/i.test(label) ||
          label==='Noch nicht geprüft' || label==='Update-Status')){
        if(!node.hidden)node.hidden=true;
        if(node.style.display!=='none')node.style.setProperty('display','none','important');
      }
      if((node.tagName==='BUTTON'||node.tagName==='A')&&
         /^(?:↻|⟳)?\s*Updates? suchen(?:\s|$)/i.test(label)){
        if(!node.hidden)node.hidden=true;
        node.style.setProperty('display','none','important');
        if(node.tagName==='BUTTON')node.disabled=true;
      }
    }
  }
'''
    updater=updater.replace(anchor,add+anchor,1)
    needle='    // Hide previous stale status rows, but retain the release notes.'
    expect_once(updater,needle,'petri-updater.js')
    updater=updater.replace(needle,'    clearLegacyStatus(card);\n'+needle,1)
    edit('petri-updater.js',updater)

    nav=original('petri445-nav.js')
    if OLD not in nav:raise ValueError('Back navigation lacks 4.4.7 marker')
    edit('petri445-nav.js',nav.replace(OLD,NEW))

    core=json.loads(original('petri-core-v4.4.7.json'))
    if core.get('version')!=OLD:raise ValueError('Mismatch in old core manifest')
    core['version']=NEW;core['base']=OLD;core['cache']='petri-core-'+NEW
    core['files']=[n.replace(OLD,NEW) for n in core['files']]
    if len(core['files'])<200 or len(core['files'])!=len(set(core['files'])):raise ValueError('Core file list incomplete/duplicated')
    core['notes']='4.4.8: consistent version meta, old update status hidden, missing detail-map links repaired; no user-data changes.'
    edit('petri-core-v4.4.8.json',json.dumps(core,ensure_ascii=False,indent=2)+'\n')

    for old,new in [('petri-offline-v4.4.7.js','petri-offline-v4.4.8.js'),('sw.js','sw.js')]:
        s=original(old)
        expect_once(s,'4.4.7' if old=='sw.js' else "const V='4.4.7'",old)
        edit(new,s.replace(OLD,NEW))

    sw=original('petri-sw.js').replace(OLD,NEW)
    m=re.search(r'const CHANGED=new Set\((\[[^\n]*\])\);',sw)
    if not m:raise ValueError('Missing worker CHANGED set')
    names=json.loads(m.group(1))
    forced=list(dict.fromkeys(names+PAGES+['petri-updater.js','petri445-nav.js','version.json','petri-sw.js','sw.js','petri-core-v4.4.8.json','petri-offline-v4.4.8.js','petri448-release.json']))
    sw=sw[:m.start()]+'const CHANGED=new Set('+json.dumps(forced,ensure_ascii=False,separators=(',',':'))+');'+sw[m.end():]
    edit('petri-sw.js',sw)

    v['version']=NEW;v['releaseDate']='2026-10-12'
    v['changes']=[
      'Falsche Meldung einer angeblich neueren identischen Version und veraltete Update-Statusanzeige ausgeblendet.',
      'Versions-Metadaten auf 37 Anwendungsseiten einheitlich auf 4.4.8 aktualisiert.',
      'Defekte Links zu detailkarte.html in Karten- und Premiumseite auf karten-detail.html korrigiert.',
      'Offline-Manifest, Service Worker und Aktualisierungsprüfung für 4.4.8 vorbereitet.',
      'Automatisierte statische Prüfung von JavaScript, JSON, HTML-Verweisen, Bildern und Offline-Dateien ergänzt.'
    ]
    v['limitations']=[
      'Statische Repository-Prüfung ist keine hundertprozentige Funktionsprüfung. Echte iPhone-, Touch-, GPS- und Netztests fehlen.',
      'Online-Satellitenbilder sind abhängig von Drittanbietern; keine amtlichen Gewässertiefen zugesichert.',
      'Vor Änderungen an lokalen Daten persönliches Backup erstellen. Dieses Update löscht keine lokalen Nutzerdaten.'
    ]
    edit('version.json',json.dumps(v,ensure_ascii=False,indent=2)+'\n')
    edit('petri448-release.json',json.dumps({'version':NEW,'baseVersion':OLD,'releaseDate':'2026-10-12','modules':['versioning','dead-links','offline','navigation-consistency'],'dataMigration':False,'pages':len(PAGES),'offlineAssets':len(core['files'])},ensure_ascii=False,indent=2)+'\n')
    edit('PRUEFBERICHT-4.4.8.txt',f'''PETRI HEIL PRO 4.4.8 - PRUEFBERICHT\n\nBasis: {OLD} und GitHub main.\n\nBehebung:\n- Falsche Versionswarnung und alter Update-Status werden aus der Ansicht entfernt.\n- Beide Kartenlinks (karte.html und premium.html) repariert.\n- {len(PAGES)} App-Seiten haben denselben Versions-Metatag und frisches Navigation-Script.\n- {len(core['files'])} Offline-Kern-Dateien im Versionsmanifest.\n- Installation loescht keine lokalen Fangdaten, Fotos oder IndexDB.\n\nGrenzen: Automatische Link-, Syntax-, JSON-, Medien- und PWA-Pruefungen,\nkeine Vollgarantie fuer saemtliche Laufzeitablaeufe. Kein echter iPhone-/GPS-/Live-Kartentest.\nSiehe GitHub Actions Pruefprotokoll fuer Ergebnisse nach Ausfuehrung.\n''')

    for path,raw in updated.items():
        t=ROOT/path;t.parent.mkdir(parents=True,exist_ok=True);t.write_bytes(raw)
    Path('/tmp/petri448-changed.txt').write_text('\n'.join(updated)+'\n',encoding='utf-8')
    print(f'PASS: {NEW}; {len(updated)} new/changed files; {len(PAGES)} pages; {len(core["files"])} offline entries')

if __name__=='__main__':
    try:patch()
    except Exception as e:print('FAIL: '+str(e),file=sys.stderr);sys.exit(2)
